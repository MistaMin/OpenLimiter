"""Turns the stored measurement results into Rust constants for the acceptance tests.
Usage: python3 make_reference.py <folder with knee_autogain.json, safe_enhance.json, attack_peakstep.json, autogain2.json>
Prints Rust source; redirect it to ../common/reference.rs."""
import json, sys, os
D = sys.argv[1]
def arr(v): return "[" + ", ".join(f"{float(x):.2f}" for x in v) + "]"
def num(s): return float(s.split()[0].replace("%", ""))
def onoff(s): return "true" if s.strip() == "On" else "false"
print("// Generated by tests/data/make_reference.py from the stored measurement results. Do not edit.")
print("// Folder: the source-A recheck folder under measurements/ (its name is not repeated here).")
k = json.load(open(os.path.join(D, "knee_autogain.json")))
print("\n/// knee_autogain.json, \"knee\": (knee dB, threshold dB, output dBFS for inputs -30..0 dBFS in 1 dB steps).")
print(f"pub const KNEE: [(f32, f32, [f64; 31]); {len(k['knee'])}] = [")
for name, v in k["knee"].items():
    a, b = name.split(", "); print(f"    ({num(a.split('Knee ')[1])}, {num(b.split('Threshold ')[1])}, {arr(v)}),")
print("];")
print("\n/// knee_autogain.json, \"auto_gain_static\": (slow hold on, peak guard on, output dBFS), threshold -6 dB.")
print(f"pub const SLOW_STATIC: [(bool, bool, [f64; 31]); {len(k['auto_gain_static'])}] = [")
for name, v in k["auto_gain_static"].items():
    a, b = name.split(", "); print(f"    ({onoff(a.split('Gain ')[1])}, {onoff(b.split('Mode ')[1])}, {arr(v)}),")
print("];")
print("\n/// knee_autogain.json, \"auto_gain_time\": (slow hold on, release ms, gain dB at the listed times in the 26 s signal).")
times = list(next(iter(k["auto_gain_time"].values())).keys())
print(f"pub const SLOW_TIME_AT_S: [f64; {len(times)}] = {arr(times)};")
print(f"pub const SLOW_TIME: [(bool, f32, [f64; {len(times)}]); {len(k['auto_gain_time'])}] = [")
for name, v in k["auto_gain_time"].items():
    a, b = name.split(", "); print(f"    ({onoff(a.split('Gain ')[1])}, {num(b.split('Release ')[1])}, {arr(v.values())}),")
print("];")
s = json.load(open(os.path.join(D, "safe_enhance.json")))
print("\npub struct GridRow { pub guard: bool, pub lift: f32, pub thr: f32, pub peak: [f64; 8], pub rms: [f64; 8], pub thd_m12: f64, pub thd_0: f64, pub settled: f64, pub half_cycles: [f64; 6], pub ms: f64 }")
print("\n/// safe_enhance.json: input steps -30, -24, -18, -12, -9, -6, -3, 0 dBFS, then the peak-step part.")
print(f"pub const GRID: [GridRow; {len(s)}] = [")
for name, v in s.items():
    a, b, c = name.split(", "); st = v["static_peak_rms_dbfs"]
    print(f"    GridRow {{ guard: {onoff(a.split('Mode ')[1])}, lift: {num(b.split('Enhance ')[1])}, thr: {num(c.split('Threshold ')[1])}, peak: {arr([x[0] for x in st.values()])}, rms: {arr([x[1] for x in st.values()])}, thd_m12: {v['thd_n_db_at_-12']}, thd_0: {v['thd_n_db_at_0']}, settled: {v['step_settled_peak_dbfs']}, half_cycles: {arr(v['step_half_cycle_peaks_db_over_settled'])}, ms: {v['step_ms_until_within_0.1_db']} }},")
print("];")
p = json.load(open(os.path.join(D, "attack_peakstep.json")))
print("\n/// attack_peakstep.json: (peak guard on, attack ms, settled peak dBFS, first sample dB over settled, first 8 half-cycle peaks, ms until within 0.1 dB).")
print(f"pub const PEAK_STEP: [(bool, f32, f64, f64, [f64; 8], f64); {len(p)}] = [")
for name, v in p.items():
    a, b = name.split(", ")
    print(f"    ({onoff(a.split('Mode ')[1])}, {num(b.split('Attack ')[1])}, {v['settled_peak_dbfs']}, {v['first_sample_db_over_settled']}, {arr(v['half_cycle_peaks_db_over_settled_first_8'])}, {v['ms_until_within_0.1_db']}),")
print("];")
g = json.load(open(os.path.join(D, "autogain2.json")))["Auto Gain On"]
print("\n/// autogain2.json, slow hold on: (burst length s, gain dB at 0.1, 0.5, 1, 2, 3, 4, 6 s after the burst, s until within 0.1 dB).")
rows = [(kk, vv) for kk, vv in g.items() if kk.startswith("burst")]
print(f"pub const SLOW_LENGTH: [(f64, [f64; 7], f64); {len(rows)}] = [")
for kk, vv in rows:
    print(f"    ({float(kk.split()[1])}, {arr([vv[t] for t in ('0.1', '0.5', '1', '2', '3', '4', '6')])}, {vv['s_until_within_0.1_db']}),")
print("];")
