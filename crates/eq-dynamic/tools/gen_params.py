#!/usr/bin/env python3
"""Writes src/params.rs: the parameter table (32 bands x 34 fields + 2 globals).
Band defaults follow OpenEQ 1.0.1 (bands 1-3 on, frequency 60 Hz x 1.75^i)."""
import struct
def f32(x): return struct.unpack('f', struct.pack('f', x))[0]
def freq(i):
    v = f32(60.0)
    p = f32(1.0)
    for _ in range(i): p = f32(p * f32(1.75))
    return min(20000.0, max(20.0, f32(v * p)))
F = [
 ("On", "On", "toggle", None),
 ("Type", "Type", "choice", "TYPES, 0"),
 ("Freq", "Frequency", "hz", None),
 ("Gain", "Gain", "new", "-30.0, 30.0, 0.0, Kind::Db"),
 ("Q", "Q", "newlog", "0.025, 40.0, 1.0, Kind::Plain"),
 ("Slope", "Slope", "new", "0.0, 100.0, 0.0, Kind::Percent"),
 ("Placement", "Placement", "choice", "PLACEMENTS, 0"),
 ("Pan", "Pan", "new", "-100.0, 100.0, 0.0, Kind::Percent"),
 ("Solo", "Solo", "toggleoff", None),
 ("Dyn", "Dynamic", "toggleoff", None),
 ("Thresh", "Threshold", "new", "-60.0, 0.0, -24.0, Kind::Db"),
 ("Range", "Range", "new", "-30.0, 30.0, 6.0, Kind::Db"),
 ("Attack", "Attack", "newlog", "1.0, 500.0, 15.0, Kind::Ms"),
 ("Release", "Release", "newlog", "1.0, 2000.0, 150.0, Kind::Ms"),
 ("Action", "Action", "choice", "ACTIONS, 0"),
 ("Knee", "Knee", "new", "0.0, 24.0, 0.0, Kind::Db"),
 ("Source", "Detector Source", "choice", "SOURCES, 0"),
 ("Relative", "Relative", "new", "0.0, 100.0, 0.0, Kind::Percent"),
 ("Lookahead", "Lookahead", "new", "0.0, 20.0, 0.0, Kind::Ms"),
 ("Transient", "Transient", "new", "0.0, 100.0, 0.0, Kind::Percent"),
 ("Auto", "Auto", "toggleoff", None),
 ("DetLink", "Detector Link", "toggleon", None),
 ("DetFreq", "Detector Frequency", "hz", None),
 ("DetQ", "Detector Q", "newlog", "0.025, 40.0, 1.0, Kind::Plain"),
 ("BelowOn", "Below On", "toggleoff", None),
 ("BelowRange", "Below Range", "new", "-30.0, 30.0, 6.0, Kind::Db"),
 ("BelowRatio", "Below Ratio", "new", "0.0, 200.0, 100.0, Kind::Percent"),
 ("AboveOn", "Above On", "toggleoff", None),
 ("AboveRange", "Above Range", "new", "-30.0, 30.0, -6.0, Kind::Db"),
 ("AboveRatio", "Above Ratio", "new", "0.0, 200.0, 100.0, Kind::Percent"),
 ("RelFree", "Relative Free", "toggleoff", None),
 ("RelFreq", "Relative Frequency", "hz", None),
 ("RelQ", "Relative Q", "newlog", "0.025, 40.0, 1.0, Kind::Plain"),
 ("RelSource", "Relative Source", "choice", "REL_SOURCES, 0"),
]
out = ["// Generated by tools/gen_params.py. Do not edit by hand.", "use olm_api::{Kind, ParamDesc};", "use crate::{TYPES, PLACEMENTS, ACTIONS, SOURCES, REL_SOURCES};", "",
       f"pub const PER_BAND: usize = {len(F)};", "pub const GLOBALS: usize = 2;", f"pub const NPARAMS: usize = 32 * PER_BAND + GLOBALS;", ""]
for k,(sfx,_,_,_) in enumerate(F):
    out.append(f"pub const F_{''.join('_'+c if c.isupper() and i else c for i,c in enumerate(sfx)).upper()}: usize = {k};")
out += ["pub const P_LOOKAHEAD_ON: usize = 32 * PER_BAND;", "pub const P_LOOKAHEAD_MS: usize = 32 * PER_BAND + 1;", "", "pub static PARAMS: [ParamDesc; NPARAMS] = ["]
for b in range(32):
    n = b + 1
    for sfx, name, kind, args in F:
        i, nm = f'"b{n}{sfx}"', f'"Band {n} {name}"'
        if kind == "toggle": out.append(f"    ParamDesc::toggle({i}, {nm}, {'true' if b < 3 else 'false'}),")
        elif kind == "toggleoff": out.append(f"    ParamDesc::toggle({i}, {nm}, false),")
        elif kind == "toggleon": out.append(f"    ParamDesc::toggle({i}, {nm}, true),")
        elif kind == "choice": out.append(f"    ParamDesc::choice({i}, {nm}, {args}),")
        elif kind == "hz": out.append(f"    ParamDesc::new({i}, {nm}, 20.0, 20000.0, {freq(b)!r}, Kind::Hz).log(),")
        elif kind == "new": out.append(f"    ParamDesc::new({i}, {nm}, {args}),")
        elif kind == "newlog": out.append(f"    ParamDesc::new({i}, {nm}, {args}).log(),")
out += ['    ParamDesc::toggle("lookaheadOn", "Global Lookahead", false),',
        '    ParamDesc::new("lookaheadMs", "Global Lookahead Time", 0.0, 20.0, 0.0, Kind::Ms),', "];"]
open("src/params.rs","w").write("\n".join(out)+"\n")
