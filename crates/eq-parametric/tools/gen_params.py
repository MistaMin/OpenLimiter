#!/usr/bin/env python3
"""Writes src/params.rs: 32 bands x 13 fields, then the globals. Defaults follow OpenEQ 1.0.1."""
import struct
def f32(x): return struct.unpack('f', struct.pack('f', x))[0]
def freq(i):
    p = f32(1.0)
    for _ in range(i): p = f32(p * f32(1.75))
    return min(20000.0, max(20.0, f32(f32(60.0) * p)))
F = [
 ("On", "On", "toggle", None), ("Type", "Type", "choice", "TYPES, 0"), ("Freq", "Frequency", "hz", None),
 ("Gain", "Gain", "new", "-30.0, 30.0, 0.0, Kind::Db"), ("Q", "Q", "newlog", "0.025, 40.0, 1.0, Kind::Plain"),
 ("Slope", "Slope", "new", "0.0, 100.0, 0.0, Kind::Percent"), ("Placement", "Placement", "choice", "PLACEMENTS, 0"),
 ("Pan", "Pan", "new", "-100.0, 100.0, 0.0, Kind::Percent"), ("Solo", "Solo", "toggleoff", None),
 ("Phase", "Phase", "new", "-100.0, 100.0, 0.0, Kind::Percent"), ("Split", "Split", "toggleoff", None),
 ("SplitTrans", "Split Transient Gain", "new", "-30.0, 30.0, 0.0, Kind::Db"),
 ("SplitTail", "Split Tail Gain", "new", "-30.0, 30.0, 0.0, Kind::Db"),
]
G = [
 ('processingMode', 'Processing Mode', 'choice', 'MODES, 0'),
 ('linearPhaseQuality', 'Linear Phase Quality', 'choice', 'QUALITIES, 1'),
 ('windowShape', 'FIR Window', 'choice', 'WINDOWS, 0'),
 ('windowParameter', 'FIR Window Tightening', 'new', '0.0, 100.0, 0.0, Kind::Percent'),
 ('mixCrossover', 'Mix Crossover', 'choice', 'CROSSOVERS, 1'),
 ('digitalPlus', 'Digital+ Steps', 'choice', 'DIGITAL_PLUS, 0'),
 ('ultraPrecision', '117-bit Precision', 'toggleoff', None),
 ('oversample2x', '2x Oversampling', 'toggleoff', None),
 ('inputGain', 'Input Trim', 'new', '-24.0, 24.0, 0.0, Kind::Db'),
 ('outputGain', 'Output Gain', 'new', '-24.0, 24.0, 0.0, Kind::Db'),
 ('gainScale', 'Gain Scale', 'new', '-200.0, 200.0, 100.0, Kind::Percent'),
 ('stereoWidth', 'Stereo Width', 'new', '0.0, 200.0, 100.0, Kind::Percent'),
 ('sideGain', 'Side Level', 'new', '-100.0, 12.0, 0.0, Kind::Db'),
 ('outputPan', 'Balance', 'new', '-100.0, 100.0, 0.0, Kind::Percent'),
 ('drive', 'Drive', 'new', '0.0, 100.0, 0.0, Kind::Percent'),
 ('polarity', 'Polarity Invert', 'toggleoff', None),
 ('autoGain', 'Auto Gain', 'toggleoff', None),
 ('bypass', 'Bypass', 'toggleoff', None),
 ('splitSource', 'Split Source', 'choice', 'SPLIT_SOURCES, 0'),
 ('splitSeparation', 'Transient Separation', 'new', '0.0, 100.0, 50.0, Kind::Percent'),
 ('splitDecay', 'Transient Decay', 'new', '0.0, 100.0, 50.0, Kind::Percent'),
 ('splitSmoothing', 'Split Smoothing', 'new', '0.0, 50.0, 5.0, Kind::Ms'),
 ('splitSolo', 'Split Solo', 'choice', 'SPLIT_SOLO, 0'),
]
def camel(s): return ''.join('_'+c if c.isupper() and i else c for i,c in enumerate(s)).upper()
out = ["// Generated by tools/gen_params.py. Do not edit by hand.", "use olm_api::{Kind, ParamDesc};", "use crate::*;", "",
       f"pub const PER_BAND: usize = {len(F)};", f"pub const GLOBALS: usize = {len(G)};", "pub const NPARAMS: usize = 32 * PER_BAND + GLOBALS;", ""]
for k,(s,_,_,_) in enumerate(F): out.append(f"pub const F_{camel(s)}: usize = {k};")
for k,(s,_,_,_) in enumerate(G): out.append(f"pub const P_{camel(s)}: usize = 32 * PER_BAND + {k};")
out += ["", "pub static PARAMS: [ParamDesc; NPARAMS] = ["]
def emit(i, nm, kind, args, on=False):
    if kind == "toggle": return f"    ParamDesc::toggle({i}, {nm}, {'true' if on else 'false'}),"
    if kind == "toggleoff": return f"    ParamDesc::toggle({i}, {nm}, false),"
    if kind == "choice": return f"    ParamDesc::choice({i}, {nm}, {args}),"
    if kind == "new": return f"    ParamDesc::new({i}, {nm}, {args}),"
    if kind == "newlog": return f"    ParamDesc::new({i}, {nm}, {args}).log(),"
for b in range(32):
    for s, name, kind, args in F:
        i, nm = f'"b{b+1}{s}"', f'"Band {b+1} {name}"'
        if kind == "hz": out.append(f"    ParamDesc::new({i}, {nm}, 20.0, 20000.0, {freq(b)!r}, Kind::Hz).log(),")
        else: out.append(emit(i, nm, kind, args, b < 3))
for s, name, kind, args in G: out.append(emit(f'"{s}"', f'"{name}"', kind, args))
out.append("];")
open("src/params.rs","w").write("\n".join(out)+"\n")
